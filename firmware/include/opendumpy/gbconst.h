#ifndef __GBCONST_H
#define __GBCONST_H

// Header Addressses
#define GBX_HEADER_ADDR  0x0100
#define GBX_HEADER_SIZE  80
#define GBX_HEADER_NINTENDO_LOGO_ADDR 0x0104
#define GBX_HEADER_NINTENDO_LOGO_SIZE 48
#define GBX_HEADER_GAME_TITLE_ADDR 0x0134
#define GBX_HEADER_GAME_TITLE_SIZE 16
#define GBX_HEADER_MFG_CODE_ADDR 0x013F
#define GBX_HEADER_MFG_CODE_SIZE 4
#define GBX_HEADER_CGB_FLAG_ADDR 0x0143
#define GBX_HEADER_NEW_LICENSEE_ADDR 0x0144
#define GBX_HEADER_NEW_LICENSEE_SIZE 2
#define GBX_HEADER_SGB_FLAG_ADDR 0X0146
#define GBX_HEADER_CART_TYPE_ADDR 0x0147
#define GBX_HEADER_ROM_SIZE_ADDR 0x0148
#define GBX_HEADER_RAM_SIZE_ADDR 0x0149
#define GBX_HEADER_DESTCODE_ADDR 0x014A
#define GBX_HEADER_OLD_LICENSEE_ADDR 0x0148
#define GBX_HEADER_MASK_ROM_VER_ADDR 0x014C
#define GBX_HEADER_GLOBAL_CS_ADDR 0x014E
#define GBX_HEADER_GLOBAL_CS_SIZE 2

// GPIO Control Pins
#define GBX_GPIO_CLK 0
#define GBX_GPIO_WR  1
#define GBX_GPIO_RD  2
#define GBX_GPIO_CS  3
#define GBX_GPIO_RST 28

// GPIO Control Masks
#define GBX_GPIO_CLK_MASK 0x0000'0000'0000'0001
#define GBX_GPIO_WR_MASK  0x0000'0000'0000'0002
#define GBX_GPIO_RD_MASK  0x0000'0000'0000'0004
#define GBX_GPIO_CS_MASK  0x0000'0000'0000'0008
#define GBX_GPIO_RST_MASK 0x0000'0000'0800'0000
#define GBX_GPIO_CTL_MASK GBX_GPIO_CLK_MASK | GBX_GPIO_WR_MASK | GBX_GPIO_RD_MASK | GBX_GPIO_CS_MASK | GBX_GPIO_RST_MASK

// Gameboy Specific Constants
#define GB_GPIO_ABUS_MASK  0x0000'0000'0000'FFFF
#define GB_GPIO_DBUS_MASK  0x0000'0000'00FF'0000
#define GB_GPIO_DBUS_BITSHIFT   28

// Gameboy Color Specific Constants
#define GBC_GPIO_ABUS_MASK 0x0000'0000'07FF'FFFF
#define GBC_GPIO_DBUS_MASK 0x0000'0000'0000'FFFF

#endif
